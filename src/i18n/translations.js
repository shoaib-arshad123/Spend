export const getCategoryIcon = (cat) => {
  if (!cat) return "📦";
  const normalized = cat.toLowerCase();
  const icons = {
    food: "🍔",
    transport: "🚌",
    books: "📚",
    health: "💊",
    entertainment: "🎮",
    clothing: "👕",
    savings: "💰",
    other: "📦",
  };
  return icons[normalized] || "📦";
};

export const getCategoryColor = (cat) => {
  if (!cat) return "#6b7280";
  const normalized = cat.toLowerCase();
  const colors = {
    food: "#f59e0b",
    transport: "#3b82f6",
    books: "#8b5cf6",
    health: "#10b981",
    entertainment: "#ec4899",
    clothing: "#f97316",
    savings: "#10b981",
    other: "#6b7280",
  };
  return colors[normalized] || "#6b7280";
};
